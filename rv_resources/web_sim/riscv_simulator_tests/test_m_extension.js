const win = dom.window;
const doc = win.document;

setTimeout(async () => {
  try {
    console.log('===========================================================');
    console.log('✖️  RV32M: MCycle.v vs the JS engine vs a BigInt reference');
    console.log('===========================================================');

    const { src, slots } = buildProgram();

    // --- 1. The assembler ---------------------------------------------
    console.log('\n[1] The program assembles');
    win.editor.value = src;
    const mc = win.assembleOnly();
    check('Assembled (' + (mc ? mc.length : 0) + ' instructions)', Array.isArray(mc) && mc.length > 0);
    const word = w => w.bytes && w.bytes.length === 4
      ? ((w.bytes[0] | (w.bytes[1] << 8) | (w.bytes[2] << 16) | (w.bytes[3] << 24)) >>> 0) : 0;
    const mWords = mc.filter(w => (word(w) & 0x7f) === 0x33 && (word(w) >>> 25) === 0x01);
    check('Every M instruction encoded with funct7 = 0000001 (' + mWords.length + ')',
      mWords.length === PAIRS.length * OPS.length);
    // Silent truncation of the IROM image is what a too-long program looks
    // like from the hardware side, so fail on the length rather than on the
    // puzzling half-finished run it produces.
    check('Program fits the Wrapper\'s 128-word IROM (' + mc.length + ')', mc.length <= 128);

    // --- 2. The JS engine ---------------------------------------------
    console.log('\n[2] The JS functional model');
    win.resetAll();
    win.assembleOnly();
    // Step to the halt loop rather than for a fixed count: every step drives a
    // full panel refresh in jsdom, so the spare ones are not free.
    let steps = 0;
    for (; steps < 400; steps++) {
      const before = win.getPc();
      win.stepOnce();
      if (win.getPc() === before) break;
    }
    console.log('     JS reached the halt loop after ' + steps + ' steps, at PC 0x' +
      (win.getPc() >>> 0).toString(16));
    check('Reached the halt loop rather than running off the end', steps < 399);
    const jsMem = slots.map(s => win.readMem(s.addr, 4) >>> 0);
    let jsBad = 0;
    slots.forEach((s, i) => {
      const want = reference(s.op, s.a, s.b);
      if (jsMem[i] !== want) {
        jsBad++;
        if (jsBad < 6) console.log('     JS  ' + s.op + ' ' + hex(s.a) + ',' + hex(s.b) +
          ' -> ' + hex(jsMem[i]) + ', reference ' + hex(want));
      }
    });
    check('All ' + slots.length + ' results match the BigInt reference', jsBad === 0);

    // --- 3. The hardware ----------------------------------------------
    console.log('\n[3] RV/*.v through Icarus');
    if (!fs.existsSync(path.join(ENGINE, 'ivl.js'))) {
      check('Engine present at ' + ENGINE + ' (set HDL_ENGINE_DIR to override)', false);
    } else {
      win.hdlSetSources(DESIGN.map(n => ({ name: n, src: fs.readFileSync(path.join(RV, n), 'utf8') })));
      const tb = win.hdlBuildTestbench({ regBankPath: win.hdlDiscoverRegBank() });
      const wrapperSrc = fs.readFileSync(path.join(RV, 'Wrapper.v'), 'utf8');
      const mem = win.hdlMemFiles(wrapperSrc);
      const icarus = await makeIcarus(tb);
      check('Design and testbench compile', icarus.ok);

      if (icarus.ok) {
        // Every signed multiply is 64 cycles and every divide 32, plus the
        // li/sw around them, so the run has to be long enough to finish.
        const out = await icarus.run(['+CYCLES=6000'], {
          'AA_IROM.mem': mem.files['AA_IROM.mem'],
          'AA_DMEM.mem': mem.files['AA_DMEM.mem'],
          'stim.mem': '', 'uart_rx.mem': ''
        });
        const trace = win.hdlParseTrace(out);
        check('Trace captured (' + trace.steps.length + ' instructions)', trace.steps.length > 100);

        // Last write wins, as in memory.
        const hw = new Map();
        for (const st of trace.steps) for (const w of st.memw) hw.set(w[0] >>> 0, w[2] >>> 0);
        check('Every result word was stored (' + hw.size + ')', hw.size >= slots.length);

        let hwBad = 0, shown = 0;
        slots.forEach((s, i) => {
          const got = hw.get(s.addr >>> 0);
          const want = reference(s.op, s.a, s.b);
          if (got !== want) {
            hwBad++;
            if (shown++ < 8) console.log('     HDL ' + s.op + ' ' + hex(s.a) + ',' + hex(s.b) +
              ' -> ' + (got === undefined ? 'not stored' : hex(got)) + ', reference ' + hex(want));
          }
        });
        check('All ' + slots.length + ' hardware results match the reference', hwBad === 0);
        check('The hardware and the JS engine agree word for word',
          slots.every((s, i) => hw.get(s.addr >>> 0) === jsMem[i]));

        // A multi-cycle instruction must retire once, not once per cycle: the
        // PC has to be frozen while Busy and the write-back has to be single.
        console.log('\n[4] The stall');
        const pcs = trace.steps.map(s => s.pc);
        check('No PC is executed twice in a row', pcs.every((p, i) => i === 0 || p !== pcs[i - 1]));
        // The trace finds register writes by shadow-comparing the array, so a
        // write of the value already there is invisible. Count the results
        // that actually change x3 rather than all of them.
        let prevX3 = 0, changing = 0;
        for (const s of slots) {
          const v = reference(s.op, s.a, s.b);
          if (v !== prevX3) changing++;
          prevX3 = v;
        }
        const x3Writes = trace.steps.reduce((n, s) =>
          n + s.regw.filter(w => w[0] === 3).length, 0);
        check('x3 changes exactly as often as the results do (' + x3Writes +
          ' of ' + slots.length + ')', x3Writes === changing);
        check('No instruction writes x3 more than once',
          trace.steps.every(s => s.regw.filter(w => w[0] === 3).length <= 1));
        // Each M instruction costs many cycles; a non-stalling core would
        // retire one per cycle like everything else.
        const mSteps = trace.steps.filter(s =>
          (s.instr & 0x7f) === 0x33 && (s.instr >>> 25) === 0x01);
        const gaps = mSteps.map(s => {
          const idx = trace.steps.indexOf(s);
          return idx + 1 < trace.steps.length ? trace.steps[idx + 1].cyc - s.cyc : null;
        }).filter(g => g !== null);
        check('Every M instruction takes more than one cycle (min ' +
          Math.min.apply(null, gaps) + ', max ' + Math.max.apply(null, gaps) + ')',
          gaps.every(g => g > 1));
        check('Signed multiply is the longest at 2*32 + 1 cycles (max ' +
          Math.max.apply(null, gaps) + ')', Math.max.apply(null, gaps) === 65);

        // --- 5. The shipped, pre-synthesised copy ---------------------
        // examples/hdl/RV_reference.v is generated from these same sources, so
        // it goes stale silently if RV/ changes and nobody reruns the build
        // script. Running the same program through it is what notices.
        console.log('\n[5] examples/hdl/RV_reference.v, the pre-synthesised core');
        const refDir = path.join(ROOT, 'examples', 'hdl');
        const refFiles = ['Wrapper.v', 'RV_reference.v']
          .map(n => ({ name: n, src: fs.readFileSync(path.join(refDir, n), 'utf8') }));
        check('The Wrapper copy is identical to RV/Wrapper.v',
          refFiles[0].src === fs.readFileSync(path.join(RV, 'Wrapper.v'), 'utf8'));
        check('Internal names are gone (no ALU1 / Src_A / shifted_op1)',
          !/\b(ALU1|Src_A|shifted_op1|temp_sum|MCycleOp)\b/.test(refFiles[1].src));

        win.hdlSetSources(refFiles);
        const refPath = win.hdlDiscoverRegBank();
        check('The register file survived the flattening: ' + refPath,
          refPath === 'dut.RV1.RegFile1.RegBank');

        const refIcarus = await makeIcarus(
          win.hdlBuildTestbench({ regBankPath: refPath }), refFiles);
        check('The reference core compiles against the fixed Wrapper', refIcarus.ok);
        if (refIcarus.ok) {
          const refOut = await refIcarus.run(['+CYCLES=6000'], {
            'AA_IROM.mem': mem.files['AA_IROM.mem'],
            'AA_DMEM.mem': mem.files['AA_DMEM.mem'],
            'stim.mem': '', 'uart_rx.mem': ''
          });
          const refTrace = win.hdlParseTrace(refOut);
          const refHw = new Map();
          for (const st of refTrace.steps) for (const w of st.memw) refHw.set(w[0] >>> 0, w[2] >>> 0);
          check('It runs the same RV32M program to the same ' + slots.length + ' results',
            slots.every(s => refHw.get(s.addr >>> 0) === reference(s.op, s.a, s.b)));
          check('It still reports register writes, so the Registers panel works',
            refTrace.steps.reduce((n, s) => n + s.regw.length, 0) > 10);
        }
      }
    }

    console.log('\n===========================================================');
    if (failed === 0) console.log('🎉 ALL ' + passed + ' RV32M TESTS PASSED!');
    else console.log('💥 ' + failed + ' RV32M TEST(S) FAILED (' + passed + ' passed)');
    process.exit(failed === 0 ? 0 : 1);
  } catch (e) {
    console.error('FATAL', e);
    process.exit(1);
  }
}, 4000);

function hex(v) { return '0x' + (v >>> 0).toString(16).padStart(8, '0'); }
