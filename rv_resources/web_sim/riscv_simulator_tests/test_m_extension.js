/*
 * RV32M end-to-end: MCycle.v against the JS engine, and both against an
 * independent BigInt reference.
 *
 * A generated straight-line program runs every one of the eight M
 * instructions over a set of awkward operand pairs (most-negative, division
 * by zero, mixed signs, operands whose product needs the full 64 bits) and
 * stores each result to data memory. The same program is then executed three
 * ways and the three sets of stored words compared:
 *
 *   1. the page's JS functional model,
 *   2. the real Icarus/WASM simulation of RV/*.v, driven by the page's own
 *      generated testbench and memory images,
 *   3. a reference computed here with BigInt, following the RISC-V
 *      specification for division by zero and for -2**31 / -1.
 *
 * Agreement between 1 and 2 is what the processor change has to preserve;
 * 3 is there so that both agreeing on something wrong still fails.
 */
