let passed = 0, failed = 0;
function check(label, cond) {
  if (cond) { passed++; console.log('  ✅ ' + label); }
  else { failed++; console.log('  ❌ ' + label); }
}

// --------------------------------------------------------------------
// The program, and the reference it is checked against
// --------------------------------------------------------------------
const DMEM_BASE = 0x10010000;
// Six pairs is what fits: the Wrapper's IROM is 2**9 bytes, so the whole
// program has to stay under 128 instructions. MCycle's own arithmetic is
// covered exhaustively by RV/test_MCycle_self_checking.v; what these have to
// reach is every decode path and the cases where the two engines could
// plausibly disagree.
const PAIRS = [
  [0xFFFFFFF9, 0x00000003],   // -7 /  3
  [0x00000007, 0xFFFFFFFD],   //  7 / -3
  [0xFFFFFFF9, 0xFFFFFFFD],   // -7 / -3
  [0x80000000, 0xFFFFFFFF],   // most negative / -1: the overflow case
  [0x12345678, 0x9ABCDEF0],   // a product that needs all 64 bits; mulhsu differs from mulhu here
  [0x00000005, 0x00000000],   // division by zero
];
const OPS = ['mul', 'mulh', 'mulhsu', 'mulhu', 'div', 'divu', 'rem', 'remu'];

const U32 = 0x100000000n;
const toS = v => (BigInt(v >>> 0) >= 0x80000000n ? BigInt(v >>> 0) - U32 : BigInt(v >>> 0));
const toU = v => BigInt(v >>> 0);
const wrap = b => Number(((b % U32) + U32) % U32) >>> 0;

function reference(op, a, b) {
  const sa = toS(a), sb = toS(b), ua = toU(a), ub = toU(b);
  switch (op) {
    case 'mul':    return wrap(sa * sb);
    case 'mulh':   return wrap((sa * sb) >> 32n);
    case 'mulhsu': return wrap((sa * ub) >> 32n);
    case 'mulhu':  return wrap((ua * ub) >> 32n);
    // RISC-V: x / 0 is all ones, x % 0 is x, and -2**31 / -1 is -2**31 rem 0.
    case 'div':    if (ub === 0n) return 0xFFFFFFFF;
                   if (sa === -(2n ** 31n) && sb === -1n) return 0x80000000;
                   return wrap(sa / sb);
    case 'divu':   return ub === 0n ? 0xFFFFFFFF : wrap(ua / ub);
    case 'rem':    if (ub === 0n) return wrap(sa);
                   if (sa === -(2n ** 31n) && sb === -1n) return 0;
                   return wrap(sa % sb);
    case 'remu':   return ub === 0n ? wrap(ua) : wrap(ua % ub);
  }
}

// x4 holds the store base; every result goes to its own word so the two
// engines can be compared word by word rather than only at the end.
function buildProgram() {
  const lines = ['# generated by test_m_extension.js', 'li x4, 0x10010000'];
  let off = 0;
  const slots = [];
  for (const [a, b] of PAIRS) {
    lines.push('li x1, 0x' + (a >>> 0).toString(16));
    lines.push('li x2, 0x' + (b >>> 0).toString(16));
    for (const op of OPS) {
      lines.push(op + ' x3, x1, x2');
      lines.push('sw x3, ' + off + '(x4)');
      slots.push({ op, a, b, addr: DMEM_BASE + off });
      off += 4;
    }
  }
  lines.push('halt: beq x0, x0, halt');
  return { src: lines.join('\n') + '\n', slots };
}

// --------------------------------------------------------------------
async function makeIcarus(testbench, sources) {
  const initIvlpp = (await import('file://' + path.join(ENGINE, 'ivlpp.js'))).default;
  const initIvl   = (await import('file://' + path.join(ENGINE, 'ivl.js'))).default;
  const initVvp   = (await import('file://' + path.join(ENGINE, 'vvp.js'))).default;

  const files = (sources ||
    DESIGN.map(n => ({ name: n, src: fs.readFileSync(path.join(RV, n), 'utf8') }))).slice();
  files.push({ name: 'cg3207_hdl_tb.v', src: testbench });

  const ppOut = [];
  const pp = await initIvlpp({ print: s => ppOut.push(s), printErr: () => {} });
  const args = ['-L'];
  for (const f of files) { pp.FS.writeFile('/' + f.name, f.src + '\n'); args.push('/' + f.name); }
  pp.callMain(args);

  const errs = [];
  const ivl = await initIvl({ print: () => {}, printErr: s => errs.push(s) });
  ivl.FS.writeFile('/ivl.conf',
    'basedir:/\nmodule:system.vpi\ngeneration:2005\ngeneration:no-specify\nout:/out.vvp\n' +
    'iwidth:32\nwidthcap:65536\nfunctor:cprop\nfunctor:nodangle\nflag:DLL=vvp.tgt\n');
  ivl.FS.writeFile('/src.v', ppOut.join('\n') + '\n');
  ivl.callMain(['-C/ivl.conf', '--', '/src.v']);

  let vvpBytes = null;
  try { vvpBytes = ivl.FS.readFile('/out.vvp'); } catch (e) {}
  const realErr = errs.filter(l => !/system\.vpi|dynamic linking not enabled/.test(l)).join('\n');
  if (!vvpBytes && realErr) console.log('    compile diagnostics:\n' + realErr);

  return {
    ok: !!vvpBytes,
    async run(plusargs, memFiles) {
      const out = [];
      const vvp = await initVvp({ print: s => out.push(s), printErr: s => out.push(s) });
      vvp.FS.writeFile('/sim.vvp', vvpBytes);
      for (const name of Object.keys(memFiles)) vvp.FS.writeFile('/' + name, memFiles[name]);
      vvp.callMain(['/sim.vvp'].concat(plusargs || []));
      return out.join('\n');
    }
  };
}

