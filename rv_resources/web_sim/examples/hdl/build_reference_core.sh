--		(vi) retain this notice in this file as well as any files derived from this.
----------------------------------------------------------------------------------
*/

HDR

# Give the netlist's top back the parameter the fixed Wrapper binds by name, and
# guard it. The generate goes inside this same module rather than in a wrapper
# around it, so that `RegFile RegFile1(...)` stays a direct instantiation of the
# core - which is how the simulator finds RegBank and shows the registers.
sed -e '/^\/\* Generated by Yosys/d' \
    -e "s|^module RV(|module RV #(parameter PC_INIT = 32'h00400000) (|" "$TMP/net.v" |
awk '
  !done && /^endmodule$/ {
    print "  generate"
    print "    if (PC_INIT != 32'"'"'h00400000) begin : pc_init_check"
    print "      this_pre_synthesised_core_only_supports_PC_INIT_00400000 u_error();"
    print "    end"
    print "  endgenerate"
    done = 1
  }
  { print }
'
} > "$OUT"

# The Wrapper is fixed and not a solution to anything, so the reference bundle
# carries its own copy rather than the page reaching into RV/.
cp RV/Wrapper.v examples/hdl/Wrapper.v

echo "wrote $OUT ($(wc -l < "$OUT") lines) and examples/hdl/Wrapper.v"
